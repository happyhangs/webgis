function amapSig(params: Record<string, string>): string {
  const sorted = Object.keys(params).sort().map(k => `${k}=${params[k]}`).join('&');
  return hexMD5(sorted + SECRET);
}

export async function geocodeAmap(address: string): Promise<{ lat: number; lng: number; name: string } | null> {
  const params: Record<string, string> = { address, key: KEY };
  params.sig = amapSig(params);
  const qs = Object.entries(params).map(([k, v]) => `${k}=${encodeURIComponent(v)}`).join('&');
  const resp = await fetch(`https://restapi.amap.com/v3/geocode/geo?${qs}`);
  const data = await resp.json();
  if (data.status !== '1' || !data.geocodes?.length) return null;
  const [lng, lat] = data.geocodes[0].location.split(',').map(Number);
  return { lat, lng, name: data.geocodes[0].formatted_address || address };
}
